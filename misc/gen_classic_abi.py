#!/usr/bin/env python3
"""
Generate the classic ABI entry points of the SPE clib4.library.

The SPE build of clib4.library is compiled for the e500's SPE, which
passes and returns float and double values in general purpose
registers.  Programs built for the classic FPU pass them in floating
point registers.  The library's "main" interface, which every classic
clib4 program uses, gets a classic entry point for each function whose
signature has a scalar float or double, or a va_list; SPE programs use
the "spe" interface, which has the functions themselves.

Input: the library's vector table, library/shared_library/clib4_vectors.h,
and the prototypes of its functions, from gcc's -aux-info of
library/shared_library/clib4.c, as "make -f GNUmakefile.os4 SPE=yes
classic-abi" writes it.

Output:
  library/shared_library/classic_abi_bridges.c   C entry points
  library/shared_library/classic_abi_variadic.S  variadic entry points
  library/shared_library/classic_abi_entries.h   their declarations
  library/shared_library/clib4_vectors.h         CLASSIC_ABI() around
                                                 the entries they replace

Run it again when a function is added to the vector table; it stops if
it finds a signature it can't bridge, or a variadic function nobody has
decided about.
"""

import os
import re
import sys

# Variadic functions that take floating point arguments, with the
# va_list function their entry point calls instead.
VARIADIC_FP = {
    "printf": "vprintf",
    "fprintf": "vfprintf",
    "sprintf": "vsprintf",
    "snprintf": "vsnprintf",
    "asprintf": "vasprintf",
    "dprintf": "vdprintf",
    "wprintf": "vwprintf",
    "fwprintf": "vfwprintf",
    "swprintf": "vswprintf",
    "syslog": "vsyslog",
    "err": "verr",
    "errx": "verrx",
    "warn": "vwarn",
    "warnx": "vwarnx",
}

# Variadic functions whose variable arguments are integers or pointers,
# which both ABIs pass the same way: they need no classic entry point.
VARIADIC_INT = {
    "open", "openat", "fcntl", "ioctl", "execl", "execle", "execlp",
    "scanf", "fscanf", "sscanf", "wscanf", "fwscanf", "swscanf",
    "ulimit", "sem_open", "spawnlp", "makecontext",
}

FLOAT_TYPES = {"float", "float_t"}
DOUBLE_TYPES = {"double", "double_t", "long double", "float64", "FLOAT64"}
VA_LIST_TYPES = {"va_list", "__gnuc_va_list", "__builtin_va_list",
                 "__va_list_tag *", "struct __va_list_tag *"}

# The classic ABI has 8 floating point argument registers, f1-f8.
MAX_FPR_ARGS = 8

HEADER = """\
/*
 * Classic ABI entry points of the SPE clib4.library.
 *
 * Generated by misc/gen_classic_abi.py from clib4_vectors.h: don't edit,
 * run it again.  See classic_abi.h.
 */
"""


def split_params(s):
    """Split a parameter list at its top level commas."""
    out, depth, cur = [], 0, ""
    for c in s:
        if c in "([":
            depth += 1
        elif c in ")]":
            depth -= 1
        if c == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += c
    if cur.strip():
        out.append(cur.strip())
    return out


def normalize(t):
    t = re.sub(r"\b(const|volatile|register|restrict|__restrict__|__restrict)\b", " ", t)
    t = re.sub(r"\s+", " ", t).strip()
    t = re.sub(r"\s*\*", " *", t)
    return t


def classify(t):
    n = normalize(t)
    if n == "...":
        return "..."
    if n in FLOAT_TYPES:
        return "F"
    if n in DOUBLE_TYPES:
        return "D"
    if n in VA_LIST_TYPES:
        return "V"
    if n == "void":
        return "void"
    if "(" in n and re.search(r"\b(float|double)\b", n):
        return "FNPTR_FP"
    return "G"


def parse_auxinfo(path):
    """Map function name -> (return type, [parameter types]), from -aux-info."""
    protos = {}
    for line in open(path):
        m = re.match(r"/\* (.*?):(\d+):\w+ \*/ (.*?);", line)
        if not m:
            continue
        decl = m.group(3).strip()
        decl = re.sub(r"^(extern|static|inline|__inline__)\s+", "", decl)
        decl = re.sub(r"^(extern|static|inline|__inline__)\s+", "", decl)
        if not decl.endswith(")"):
            continue
        # The parameter list: the parenthesised group at the end.
        depth, i = 0, len(decl) - 1
        while i >= 0:
            if decl[i] == ")":
                depth += 1
            elif decl[i] == "(":
                depth -= 1
                if depth == 0:
                    break
            i -= 1
        params, head = decl[i + 1:-1], decl[:i].rstrip()
        m2 = re.match(r"(.*?)\b(\w+)$", head)
        if not m2:
            continue                # a declarator like signal()'s
        ret, name = m2.group(1).strip(), m2.group(2)
        if name in protos:
            continue
        plist = [] if params.strip() in ("", "void") else split_params(params)
        protos[name] = (ret, plist, m.group(1))
    return protos


VEC_RE = re.compile(r"^(\s*\(void \*\)\s*)(?:CLASSIC_ABI)?\(\s*(\w+)\s*\)(.*)$")


def vector_names(lines):
    names = []
    for line in lines:
        m = VEC_RE.match(line)
        if m:
            names.append(m.group(2))
    return names


def decl_param(t, name):
    t = t.strip()
    if "(" in t or "[" in t:
        return "__typeof__(%s) %s" % (t, name)
    return "%s %s" % (t, name)


def bridge(name, ret, params):
    """The declaration and C source of the classic entry point of name(),
    or (None, None) if it needs none."""
    kinds = [classify(p) for p in params]
    rkind = classify(ret)
    if "..." in kinds:
        return None, None
    if "FNPTR_FP" in kinds or rkind == "FNPTR_FP":
        sys.exit("%s: takes or returns a function with floating point arguments: "
                 "can't bridge it" % name)
    if rkind not in ("F", "D") and not any(k in ("F", "D", "V") for k in kinds):
        return None, None

    fpr, formals, args, copies = 0, [], [], []
    for i, (t, k) in enumerate(zip(params, kinds)):
        a = "a%d" % (i + 1)
        if k in ("F", "D"):
            fpr += 1
            if fpr > MAX_FPR_ARGS:
                sys.exit("%s: more than %d floating point arguments" % (name, MAX_FPR_ARGS))
            args.append(("(float) " if k == "F" else "") + "CLASSIC_FPR(%d)" % fpr)
        elif k == "V":
            formals.append("va_list " + a)
            copies.append(a)
            args.append("ap%d" % (i + 1))
        else:
            formals.append(decl_param(t, a))
            args.append(a)

    call = "(%s)(%s)" % (name, ", ".join(args))
    proto = "%s(%s)" % (name, ", ".join(params) or "void")
    out = ["/* %s %s */" % (ret, proto)]
    sig = "__classic_%s(%s)" % (name, ", ".join(formals) or "void")
    if rkind in ("F", "D"):
        rtype = "void"
    else:
        rtype = ret
    if not copies:
        if rkind in ("F", "D"):
            body = "    CLASSIC_RETURN_FPR(%s);" % call
        elif rkind == "void":
            body = "    %s;" % call
        else:
            body = "    return %s;" % call
    else:
        lines = []
        for a in copies:
            n = a[1:]
            lines.append("    va_list ap%s;" % n)
        if rkind not in ("void", "F", "D"):
            lines.append("    %s r;" % ret)
        elif rkind in ("F", "D"):
            lines.append("    double r;")
        for a in copies:
            lines.append("    CLASSIC_VA_COPY(ap%s, %s);" % (a[1:], a))
        if rkind == "void":
            lines.append("    %s;" % call)
        else:
            lines.append("    r = %s;" % call)
        for a in copies:
            lines.append("    va_end(ap%s);" % a[1:])
        if rkind in ("F", "D"):
            lines.append("    CLASSIC_RETURN_FPR(r);")
        elif rkind != "void":
            lines.append("    return r;")
        body = "\n".join(lines)
    out.append("%s %s {\n%s\n}" % (rtype, sig, body))
    return "%s %s;" % (rtype, sig), "\n".join(out)


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: gen_classic_abi.py <library dir> <aux-info file>")
    libdir, auxinfo = sys.argv[1], sys.argv[2]
    vec_path = os.path.join(libdir, "shared_library", "clib4_vectors.h")
    vec_lines = open(vec_path).read().split("\n")
    names = vector_names(vec_lines)
    protos = parse_auxinfo(auxinfo)

    bridged, variadic, headers, errors = set(), [], set(), []
    decls = {}
    c_out = []
    seen = set()
    for name in names:
        if name in seen or name in ("NULL", "libReserved"):
            continue
        seen.add(name)
        if name not in protos:
            continue
        ret, params, where = protos[name]
        if "..." in [classify(p) for p in params]:
            if name in VARIADIC_FP:
                target = VARIADIC_FP[name]
                kinds = [classify(p) for p in params[:-1]]
                if any(k != "G" for k in kinds):
                    errors.append("%s: named arguments that aren't integers or pointers" % name)
                if target not in seen and target not in names:
                    errors.append("%s: %s isn't in the vector table" % (name, target))
                variadic.append((name, target, len(params) - 1))
                bridged.add(name)
            elif name not in VARIADIC_INT:
                errors.append("%s: variadic, in neither VARIADIC_FP nor VARIADIC_INT" % name)
            continue
        decl, src = bridge(name, ret, params)
        if src:
            c_out.append(src)
            decls[name] = decl
            bridged.add(name)
            m = re.search(r"/include/(.*)$", where)
            if m:
                headers.add(m.group(1))
    if errors:
        sys.exit("\n".join(errors))

    with open(os.path.join(libdir, "shared_library", "classic_abi_bridges.c"), "w") as f:
        f.write(HEADER + "\n")
        f.write("/* The declarations clib4.c has, like log2()'s */\n#define shared_comp\n\n")
        for h in sorted(headers):
            f.write("#include <%s>\n" % h)
        f.write('\n#include "classic_abi.h"\n#include "classic_abi_entries.h"\n\n')
        f.write("\n\n".join(c_out) + "\n")

    with open(os.path.join(libdir, "shared_library", "classic_abi_variadic.S"), "w") as f:
        f.write(HEADER.replace("entry points", "entry points of variadic functions", 1) + "\n")
        f.write('#include "classic_abi.h"\n\n\t.text\n\n')
        f.write("/*\tfunction, va_list function, named arguments */\n")
        for name, target, named in variadic:
            f.write("\tCLASSIC_VARIADIC %s, %s, %d\n" % (name, target, named))

    with open(os.path.join(libdir, "shared_library", "classic_abi_entries.h"), "w") as f:
        f.write(HEADER.replace("entry points of", "entry points in the vector table of", 1) + "\n")
        f.write("#ifndef _CLASSIC_ABI_ENTRIES_H\n#define _CLASSIC_ABI_ENTRIES_H\n\n")
        f.write("/* in classic_abi_bridges.c */\n")
        for name in names:
            if name in decls:
                f.write(decls[name] + "\n")
        f.write("\n/* in classic_abi_variadic.S */\n")
        for name, target, named in variadic:
            f.write("void __classic_%s(void);\n" % name)
        f.write("\n#endif /* _CLASSIC_ABI_ENTRIES_H */\n")

    out = []
    for line in vec_lines:
        m = VEC_RE.match(line)
        if m:
            name = m.group(2)
            entry = ("CLASSIC_ABI(%s)" if name in bridged else "(%s)") % name
            text = m.group(1) + entry + m.group(3).split("/*")[0].strip()
            col = line.find("/*")
            if col >= 0:
                # keep the offset comments in their column
                text = text.ljust(max(col, len(text) + 1)) + line[col:]
            out.append(text)
        else:
            out.append(line)
    with open(vec_path, "w") as f:
        f.write("\n".join(out))

    print("%d C entry points, %d variadic entry points" % (len(c_out), len(variadic)))


if __name__ == "__main__":
    main()
